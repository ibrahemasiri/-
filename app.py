# نموذج الإجابات التفاعلي
user_answers = {}
with st.form("quiz_form"):
    for idx, q in enumerate(questions):
        st.subheader(q["question"])
        user_answers[idx] = st.radio(f"اختر الإجابة الصحيحة:", q["options"], key=idx)
        st.write("---")
    
    submitted = st.form_submit_button("تسليم الاختبار وتقييم الدرجة 🎯")

if submitted:
    score = 0
    for idx, q in enumerate(questions):
        if user_answers[idx] == q["answer"]:
            score += 1
    
    st.balloons()
    st.success(f"🎉 كفو! درجتك النهائية هي: {score} من {len(questions)}")
    if score == 10:
        st.balloons()
